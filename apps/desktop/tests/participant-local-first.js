const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { shouldRenderParticipantCaption, LOCAL_CAPTION_STALE_MS } = require('../transcriber/participantCaptionPriority');
const now = 100000;
const local = { source: 'local-meet', lastLocalAt: now, lastHostRelayAt: now, now };
assert(shouldRenderParticipantCaption(local), 'Local caption is always displayed immediately');
assert(shouldRenderParticipantCaption({ ...local, lastLocalAt: 0 }), 'Local IPC does not depend on a relay');
assert(!shouldRenderParticipantCaption({ ...local, source: 'host-relay' }), 'Live local captions beat host relay');
assert(!shouldRenderParticipantCaption({ ...local, source: 'peer-relay' }), 'Live local captions beat peer relay');
assert(!shouldRenderParticipantCaption({ source: 'host-relay', lastLocalAt: now - LOCAL_CAPTION_STALE_MS + 1, now }));
assert(shouldRenderParticipantCaption({ source: 'host-relay', lastLocalAt: now - LOCAL_CAPTION_STALE_MS, now }), 'Stale local feed allows remote fallback');
assert(shouldRenderParticipantCaption({ source: 'host-relay', lastLocalAt: 0, now }), 'Remote captions work before Meet CC is ready');
assert(!shouldRenderParticipantCaption({ source: 'peer-relay', lastLocalAt: 0, lastHostRelayAt: now, now }), 'Host fallback wins over peer');
assert(shouldRenderParticipantCaption({ source: 'peer-relay', lastLocalAt: 0, lastHostRelayAt: now - 2000, now }), 'Peer fallback works when host fails');
assert(!shouldRenderParticipantCaption({ source: 'unknown', lastLocalAt: 0, now }));
const main = fs.readFileSync(path.resolve(__dirname, '../main.js'), 'utf8');
const localIPCStart = main.indexOf("ipcMain.on('meet-caption-message'");
const localIPCEnd = main.indexOf("ipcMain.handle('send-meet-chat-message'", localIPCStart);
assert(localIPCStart >= 0 && localIPCEnd > localIPCStart);
const localIPC = main.slice(localIPCStart, localIPCEnd);
assert.match(localIPC, /overlayWindow\.webContents\.send\('transcript',/);
assert(!localIPC.includes('Date.now() - hostRelayLastAt > 1800'), 'Local captions must never wait for Railway host freshness');
assert(localIPC.includes('sendLocalCaption('), 'Local text must still be sent for PDF persistence');
const relayStart = main.indexOf('startRemoteTranscriptStream({');
const relayEnd = main.indexOf('onAudioChunk(pcmBuffer => {', relayStart);
assert(relayStart >= 0 && relayEnd > relayStart);
assert(main.slice(relayStart, relayEnd).includes('shouldRenderParticipantCaption({'), 'Railway feed must only be used as fallback');
assert(main.includes('const DEEPGRAM_FALLBACK_ENABLED = false;'));
console.log(JSON.stringify({ ok: true, localFirst: true, relayFallback: true, pdfPersistence: true, deepgramOff: true }));
